let currentLang;

function t(key, vars) {
  let str = (LANG[currentLang] && LANG[currentLang][key]) || LANG.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => { str = str.replace(`{${k}}`, vars[k]); });
  }
  return str;
}

function setLang(code) {
  if (!LANG[code]) return;
  currentLang = code;
  localStorage.setItem("lang", code);
  applyLang();
}

function initLang() {
  currentLang = localStorage.getItem("lang") || "en";
  applyLang();
  renderLangSelector();
}

function applyLang() {
  document.getElementById("greeting-sub").textContent = t("welcomeSub");
  setGreeting(currentGuestName);
  updateWeatherLabels();
  updateCardTitles();
  updateForecastDays();
  renderLangSelector();
}

function updateForecastDays() {
  const days = LANG[currentLang]?.days || LANG.en.days;
  document.querySelectorAll(".forecast-day-name").forEach((el, i) => {
    if (days[i]) el.textContent = days[i];
  });
}

function updateCardTitles() {
  document.querySelectorAll(".card[data-card-id]").forEach(card => {
    const id = card.getAttribute("data-card-id");
    const title = card.querySelector(".card-title");
    if (title) title.textContent = t(id);
  });
}

function updateWeatherLabels() {
  const labels = document.querySelectorAll(".weather-stat-label");
  if (labels.length >= 3) {
    labels[0].textContent = t("humidity");
    labels[1].textContent = t("wind");
    labels[2].textContent = t("feelsLike");
  }
  const err = document.getElementById("weather-loading");
  if (err && err.textContent && err.textContent !== t("loading")) {
    err.textContent = t("weatherUnavailable");
  }
  if (typeof currentWeatherCode !== "undefined" && currentWeatherCode !== null) {
    const desc = document.getElementById("weather-desc");
    const codes = LANG[currentLang]?.weatherCodes || LANG.en.weatherCodes;
    if (desc && codes[currentWeatherCode]) desc.textContent = codes[currentWeatherCode];
  }
}

function renderLangSelector() {
  const current = document.getElementById("lang-current");
  const menu = document.getElementById("lang-menu");
  if (!current || !menu) return;

  const lang = LANGS.find(l => l.code === currentLang);
  current.textContent = lang ? lang.label : "English";

  menu.innerHTML = LANGS.map(l =>
    `<button class="lang-opt${l.code === currentLang ? " active" : ""}" onclick="selectLang('${l.code}')">${l.label}</button>`
  ).join("");
}

function toggleLangMenu() {
  const menu = document.getElementById("lang-menu");
  if (!menu) return;
  menu.style.display = menu.style.display === "none" ? "" : "none";
}

function selectLang(code) {
  setLang(code);
  document.getElementById("lang-menu").style.display = "none";
}
